from typing import Optional, Dict, Any
from pydantic import BaseModel, Field

class AIGenerationRequest(BaseModel):
    """Input parameters for free-form or guided text generation."""
    prompt: str = Field(..., description="Main prompt or instruction")
    system_prompt: Optional[str] = Field(default=None, description="System instructions")
    temperature: Optional[float] = Field(default=None, description="Sampling temperature override")
    max_tokens: Optional[int] = Field(default=None, description="Max response tokens")

class AIGenerationResponse(BaseModel):
    """Output container for LLM generation."""
    content: str = Field(..., description="Raw text generated by the model")
    model: str = Field(..., description="Model identifier used")
    provider: str = Field(..., description="Provider name")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Diagnostic/usage metadata")

class AIHealthStatus(BaseModel):
    """Health status representation of the AI provider."""
    provider: str
    model: str
    is_reachable: bool
    is_model_available: bool
    status: str
    message: Optional[str] = None
